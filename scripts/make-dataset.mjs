/** Zenodo 에 올릴 배포물을 만든다 — `dist-dataset/`.
 *
 *  ★★ **NIST 원표를 넣지 않는 것이 이 스크립트의 요점이다.** `src/data/attenuation.json` 은
 *    NIST Standard Reference Database 126 이고 쪽에 「All rights reserved」가 붙어 있다
 *    (2026-09-16 원문 확인, 경위는 `docs/zenodo.md`). 제품에 넣어 **계산에 쓰는 것**과
 *    **표를 데이터셋으로 재배포하는 것**은 다른 층이다. 대신 수확 스크립트를 함께 실어
 *    쓰는 사람이 NIST 에서 직접 받게 한다 — 재현은 막히지 않는다.
 *  ★ 사람이 기억으로 지키면 반드시 샌다. 그래서 **만드는 자리에서 빼고**, 마지막에
 *    **배포물 전체를 훑어 μ/ρ 가 섞이지 않았는지 확인**한다(아래 ④).
 *
 *  실행: npm run make-dataset
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { NUCLIDES, ATTEN, MATERIALS, nuclidePage, ALL_KEYS, longName } from "../src/lib/nuclides.ts";
import { SOURCE_CITATIONS } from "../brand.ts";

const OUT = "dist-dataset";
rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, "code"), { recursive: true });

/* ── ① 파생 결과 — 이 작업의 알맹이이고 온전히 우리 것이다 ─────── */
const shields = [];
const lines = [];
for (const key of ALL_KEYS) {
  const p = nuclidePage(key);
  for (const s of p.shields)
    shields.push({ nuclide: key, material: s.material, hvl_mm: +(s.hvlCm * 10).toPrecision(6),
                   tvl_mm: +(s.tvlCm * 10).toPrecision(6), tvl_over_hvl: +s.ratio.toPrecision(6) });
  for (const s of p.shares)
    lines.push({ nuclide: key, energy_keV: s.eKeV, emission_probability_pct: s.yPct,
                 dose_share: +s.share.toPrecision(6) });
}
writeFileSync(join(OUT, "spectrum-shielding.json"), JSON.stringify(shields, null, 1) + "\n");
writeFileSync(join(OUT, "line-dose-shares.json"), JSON.stringify(lines, null, 1) + "\n");

/* ── ② IAEA 에서 파생한 핵종 표 — 약관이 재배포를 허용한다 ───────── */
const table = ALL_KEYS.map((k) => {
  const n = NUCLIDES[k], p = nuclidePage(k);
  return {
    nuclide: k, name: longName(k), z: n.z, a: n.a, isomer: n.iso || null,
    half_life_s: n.t_half_s, decay_mode: n.decay,
    specific_activity_Bq_per_g: n.sa_bq_g,
    gamma_constant_mGy_m2_per_GBq_h: n.gamma_const,
    mean_photon_keV: Number.isFinite(p.meanPhotonKeV) ? +p.meanPhotonKeV.toPrecision(6) : null,
    beta_max_keV: n.beta_max_keV ?? null, beta_mean_keV: n.beta_mean_keV ?? null,
    photon_lines: n.lines, beta_branches: n.beta ?? null, alpha_lines: n.alpha ?? null,
  };
});
writeFileSync(join(OUT, "nuclides.json"), JSON.stringify(table, null, 1) + "\n");

/* ── ③ 코드 — 엔진과 수확 스크립트. **감쇠 자료는 빼고 스크립트만** ── */
for (const f of ["src/engine", "src/lib/nuclides.ts", "src/lib/nuclide-prose.ts",
                 "scripts/harvest.py", "scripts/nist.py", "scripts/fill.py"])
  if (existsSync(f)) cpSync(f, join(OUT, "code", f.replace(/^src\/|^scripts\//, "")), { recursive: true });

const readme = `# ${"RadCalc"} — nuclide reference data and spectrum-solved shielding

Generated by \`npm run make-dataset\` from the source repository.

## Files

| File | What it is |
|---|---|
| \`nuclides.json\` | 147 nuclides: half-life, decay mode, specific activity, photon/beta/alpha lines |
| \`spectrum-shielding.json\` | Half- and tenth-value layers solved across the whole emission spectrum, for ${MATERIALS.length} materials |
| \`line-dose-shares.json\` | Each photon line's share of the air kerma rate |
| \`code/\` | The engine that computes the above, and the harvest scripts |

## What is deliberately NOT here

The NIST photon attenuation tables are **not redistributed**. They are
${SOURCE_CITATIONS[1].terms}
Run \`code/nist.py\` to fetch them from NIST directly and write \`code/data/attenuation.json\`; the
engine imports that path and then reproduces every figure here. Until you do, the code in \`code/\`
will not run — that is deliberate, not an omission.

## Sources and terms

**Decay data** — ${SOURCE_CITATIONS[0].text}
${SOURCE_CITATIONS[0].terms}

**Attenuation coefficients** — ${SOURCE_CITATIONS[1].text}
See <${SOURCE_CITATIONS[1].url}>.

## Method

Half-value layers are solved for the whole spectrum: every photon line above the 20 keV cutoff is
attenuated with its own coefficient and the thickness that leaves half of the total air kerma rate
is found numerically. This differs from reading a single-energy table wherever the dose rate is not
dominated by one line. All figures are **narrow beam** — scattered radiation is not added back, so a
shield designed to these numbers will pass more than they suggest.

Licence: see LICENSE in the source repository. The licence covers this contribution only; the
underlying evaluated data remain the work of the bodies credited above.
`;
writeFileSync(join(OUT, "README.md"), readme);

/* ── ④ **배포물을 훑는다 — 두 가지를 가른다** ───────────────────
   ★★ 처음에 「`attenuation.json` 을 언급하면 결함」으로 셌더니 **`import` 문 네 개가 걸렸다.**
     그것은 라이선스 문제가 아니라 **배포물이 그대로는 안 돌아간다**는 뜻이다 — 다른 사실이다.
     ① **수치가 실려 있으면 결함**(재배포다) ② **참조만 있으면 수확 단계가 필요하다는 뜻**이고,
     그렇다면 README 가 그 단계를 설명하고 있어야 한다. 섞어 세면 둘 다 못 고친다. */
const walk = (d) => readdirSync(d, { withFileTypes: true })
  .flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const files = walk(OUT);
const TEXT = /\.(json|ts|js|mjs|py|md|csv)$/;
/** 원표의 지문 — 납 표의 앞 네 줄을 **숫자열**로 든다.
 *  ★★ 처음에는 글자로 비교했다가 **역테스트에서 안 잡혔다** — 파일에는 `5210.0` 인데
 *    파싱하면 `5210` 이라 글자열이 다르다. 서식(뒤 `.0`·지수 표기)에 흔들리지 않으려면
 *    **숫자로 견줘야 한다.** 이 레포가 되풀이해 배운 것과 같다: 비교하는 자를 고를 때
 *    그 자가 실제 실패 모드를 재는지 **역테스트로 확인할 것.** */
const FINGERPRINT = ATTEN.lead.slice(0, 4).flat();
const numsOf = (s) => (s.match(/-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?/g) ?? []).map(Number);
const hasRun = (hay, needle) => {
  for (let i = 0; i + needle.length <= hay.length; i++) {
    let ok = true;
    for (let j = 0; j < needle.length; j++)
      if (Math.abs(hay[i + j] - needle[j]) > Math.abs(needle[j]) * 1e-12) { ok = false; break; }
    if (ok) return true;
  }
  return false;
};
const carries = [], refers = [];
for (const f of files) {
  if (!TEXT.test(f)) continue;
  const s = readFileSync(f, "utf8");
  if (hasRun(numsOf(s), FINGERPRINT)) carries.push(f);
  else if (/attenuation\.json/.test(s)) refers.push(f);
}
if (carries.length) {
  console.error(`\n❌ NIST 원표의 수치가 배포물에 실려 있다 — 재배포다(docs/zenodo.md 2절):`);
  for (const f of carries) console.error("   " + relative(OUT, f));
  process.exit(1);
}
const readmeText = readFileSync(join(OUT, "README.md"), "utf8");
if (refers.length && !/nist\.py/.test(readmeText)) {
  console.error(`\n❌ 배포물이 감쇠 자료를 참조하는데(${refers.length}개 파일) README 가 받는 법을 안 적었다`);
  process.exit(1);
}
const total = files.reduce((a, f) => a + statSync(f).size, 0);
console.log(`\n✅ ${OUT}/ — 파일 ${files.length}개 · ${(total / 1e6).toFixed(2)} MB`);
console.log(`   핵종 ${table.length} · 차폐 행 ${shields.length} · 선 ${lines.length}`);
console.log(`   NIST 원표 수치 0건 · 참조 ${refers.length}개 파일 → README 가 수확 절차를 든다`);
