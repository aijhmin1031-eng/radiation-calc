const T = nuclides as unknown as Record<string, { t_half_s: number }>;

/** ★ **반감기 1초 미만은 쪽을 세우지 않는다**(2026-09-21 의 noindex 규칙을 이어받는다).
 *  차폐는 설계하는 데 시간이 걸리는 일이라, 반감기가 1초에 못 미치면 「납 몇 mm」라는 물음 자체가 성립하지 않는다 —
 *  계산은 맞지만 답할 물음이 없다(Cd-109m2 는 10.6 µs 다). 그런 핵종은 지금 목록에 하나도 없으므로 이 값은
 *  **목록을 늘릴 때의 문지기**다 — 아래 검사가 빌드를 멈춘다. 조용히 빼지 않는 것은, 목록에 적은 쪽이 말없이
 *  안 서면 「넣었는데 왜 없지」를 아무도 못 찾기 때문이다. */
export const MIN_HALF_LIFE_S = 1;

/* 목록을 고칠 때의 실수 둘을 **빌드에서** 막는다 — 오타(자료에 없는 키)는 쪽이 조용히 빠지고,
   1초 미만은 위 규칙을 어긴다. 이 파일을 읽는 모든 자리(쪽·게이트)가 같은 자리에서 멈춘다. */
for (const k of PUBLISHED) {
  if (!T[k]) throw new Error(`nuclide-pages: 자료에 없는 핵종이 PUBLISHED 에 있다 — ${k}`);
  if (T[k].t_half_s < MIN_HALF_LIFE_S)
    throw new Error(`nuclide-pages: 반감기 ${T[k].t_half_s} s 인 ${k} 는 쪽을 세우지 않는다(하한 ${MIN_HALF_LIFE_S} s)`);
}

/** 그 핵종에 참조 쪽이 있는가. */
export const hasPage = (key: string) => PUBLISHED.has(key);

/** 쪽이 있는 핵종 — **자료 순서 그대로**(목록 표·사이트맵·게이트가 같은 순서를 본다). */
export const PAGE_KEYS: readonly string[] = Object.keys(T).filter(hasPage);

/** ★★ 핵종 쪽 주소의 **유일한 출처**. 쪽이 없으면 `null` — 그러면 그리는 자리는 링크 없이 이름만 낸다.
 *  base 없는 정본 경로를 돌려준다(그릴 때 `u()` 가 붙인다 — `components/NuclideRef.astro`).
 *  ★ 슬러그 규칙은 `lib/nuclides.ts` 의 `slugOf` 와 같다(`key.toLowerCase()`). 거기서 가져오지 않는 것은
 *    그 모듈이 엔진과 감쇠 자료를 함께 끌고 오기 때문이다 — 이 파일은 게이트도 읽는다. */
export const nuclidePath = (key: string): string | null =>
  hasPage(key) ? `/nuclides/${key.toLowerCase()}/` : null;
